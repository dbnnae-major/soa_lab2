CREATE TABLE IF NOT EXISTS soa_lab2_dragon (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(name) > 0),
    coordinates_x BIGINT NOT NULL CHECK (coordinates_x > -843),
    coordinates_y REAL NOT NULL,
    creation_date TIMESTAMP WITH TIME ZONE NOT NULL,
    age INTEGER CHECK (age > 0),
    wingspan BIGINT NOT NULL CHECK (wingspan > 0),
    speaking BOOLEAN NOT NULL,
    color TEXT CHECK (color IN ('GREEN', 'BLUE', 'YELLOW', 'ORANGE')),
    killer_name TEXT CHECK (length(killer_name) > 0),
    killer_birthday TIMESTAMP WITH TIME ZONE,
    killer_nationality TEXT CHECK (killer_nationality IN ('FRANCE', 'ITALY', 'JAPAN')),
    CHECK (killer_name IS NOT NULL OR (killer_birthday IS NULL AND killer_nationality IS NULL))
);
